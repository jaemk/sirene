// Generates crates/sirene-core/src/math/svg_data.rs and the fixture
// crates/sirene-core/tests/fixtures/math/katex-svg.json from KaTeX's SVG geometry.
// Development tool: both outputs are checked in.
//
// Setup (once): the KaTeX checkout described in scripts/katex-fixtures.mjs, at tag v0.19.1.
// Run:
//   node scripts/katex-svg.mjs
//
// KaTeX's `src/svgGeometry.ts` holds a table of fixed path data (`path`) and builders that take
// parameters (`sqrtPath`, `innerPath`, `tallDelim`, `phasePath`). Node 24 reads the TypeScript
// directly, so this script imports that module. The Rust table holds the `path` entries sorted by
// name. The fixture holds the table size and KaTeX's output for several parameter sets of each
// builder, which the Rust ports must reproduce exactly. Adapted from KaTeX, MIT licensed,
// Copyright (c) 2013-2020 Khan Academy and other contributors; see THIRD-PARTY-NOTICES.

import { writeFileSync } from "node:fs";

const { path, sqrtPath, innerPath, tallDelim, phasePath } = await import(
  new URL("../local/katex/src/svgGeometry.ts", import.meta.url)
);

function rustString(s) {
  if (s.includes('"#')) throw new Error("path data contains a raw string terminator");
  return `r#"${s}"#`;
}

const names = Object.keys(path).sort((a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b)));
const rows = names.map((name) => `    (${rustString(name)}, ${rustString(path[name])}),`).join("\n");

const out = `// GENERATED by scripts/katex-svg.mjs from KaTeX's src/svgGeometry.ts (v0.19.1). Do not edit:
// change the script and run it again. Adapted from KaTeX, MIT licensed, Copyright (c) 2013-2020
// Khan Academy and other contributors; see THIRD-PARTY-NOTICES.
//
// KaTeX's fixed SVG path data for stretchy arrows, braces, and accents, in a 1000-units-per-em
// view box. Entries are sorted by the bytes of the name, and a test checks it.

/// Each entry is a name and its SVG path data.
pub(crate) static PATHS: &[(&str, &str)] = &[
${rows}
];

/// The path data for a stretchy shape's name, if KaTeX has one.
pub(crate) fn path(name: &str) -> Option<&'static str> {
    PATHS
        .binary_search_by(|(key, _)| (*key).cmp(name))
        .ok()
        .and_then(|i| PATHS.get(i))
        .map(|(_, data)| *data)
}
`;
writeFileSync(new URL("../crates/sirene-core/src/math/svg_data.rs", import.meta.url), out);

const sqrtSizes = ["sqrtMain", "sqrtSize1", "sqrtSize2", "sqrtSize3", "sqrtSize4", "sqrtTall"];
const extras = [0, 0.04, 0.0625, 0.1234];
const sqrt = [];
for (const size of sqrtSizes) {
  for (const extra of extras) {
    const height = size === "sqrtTall" ? 3000 + extra * 1000 : 1080;
    sqrt.push({ size, extra, height, path: sqrtPath(size, extra, height) });
  }
}

const innerNames = ["⎜", "∣", "∥", "⎟", "⎢", "⎥", "⎪", "⏐", "‖", "x"];
const inner = [];
for (const name of innerNames) {
  for (const height of [0, 300, 1234.5]) {
    inner.push({ name, height, path: innerPath(name, height) });
  }
}

const tallNames = [
  "lbrack", "rbrack", "vert", "doublevert", "lfloor", "rfloor", "lceil", "rceil", "lparen", "rparen",
];
const tall = [];
for (const label of tallNames) {
  for (const mid of [0, 200, 1234.5]) {
    tall.push({ label, mid, path: tallDelim(label, mid) });
  }
}

const phase = [0, 400, 1000, 1234.5].map((y) => ({ y, path: phasePath(y) }));

const spot = Object.fromEntries(["leftarrow", "vec", "longequal", "rightbracketover"].map((n) => [n, path[n]]));

const fixture = { count: names.length, names, spot, sqrt, inner, tall, phase };
writeFileSync(
  new URL("../crates/sirene-core/tests/fixtures/math/katex-svg.json", import.meta.url),
  JSON.stringify(fixture, null, 1) + "\n",
);
console.log(`${names.length} paths; ${sqrt.length} sqrt, ${inner.length} inner, ${tall.length} tall, ${phase.length} phase cases`);
