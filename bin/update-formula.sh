#!/usr/bin/env bash
# Regenerate the Homebrew formula for a release.
#
# Usage: update-formula.sh <version> <dist-dir> <out-file>
#   <version>   release version without the leading 'v' (e.g. 0.1.0)
#   <dist-dir>  directory containing sirene-<version>-<target>.tar.gz tarballs
#   <out-file>  formula path to write (e.g. Formula/sirene.rb)
#
# Invoked by .github/workflows/release.yml; the formula it writes must match the
# committed Formula/sirene.rb byte-for-byte except for the version, urls, and
# sha256 values, so releases produce a clean diff.
set -euo pipefail

version="$1"
dist="$2"
out="$3"
repo="jaemk/sirene"
base="https://github.com/${repo}/releases/download/v${version}"

sha() {
  local file="${dist}/sirene-${version}-$1.tar.gz"
  [ -f "$file" ] || { echo "missing $file" >&2; exit 1; }
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$file" | awk '{print $1}'
  else
    shasum -a 256 "$file" | awk '{print $1}'
  fi
}

mac_arm="$(sha aarch64-apple-darwin)"
mac_x86="$(sha x86_64-apple-darwin)"
lin_arm="$(sha aarch64-unknown-linux-gnu)"
lin_x86="$(sha x86_64-unknown-linux-gnu)"

mkdir -p "$(dirname "$out")"
cat > "$out" <<EOF
# Auto-generated by .github/workflows/release.yml on each tagged release.
# The version, urls, and sha256 values are overwritten there; do not edit by hand.
class Sirene < Formula
  desc "Mermaid diagram editor and viewer with terminal output"
  homepage "https://github.com/${repo}"
  version "${version}"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "${base}/sirene-${version}-aarch64-apple-darwin.tar.gz"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "${base}/sirene-${version}-x86_64-apple-darwin.tar.gz"
      sha256 "${mac_x86}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/sirene-${version}-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "${lin_arm}"
    end
    on_intel do
      url "${base}/sirene-${version}-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "${lin_x86}"
    end
  end

  def install
    bin.install "sirene"
  end

  test do
    system "#{bin}/sirene", "--version"
  end
end
EOF

echo "wrote ${out} for v${version}"
